
-- =====================================================
-- ENERGY_INTELLIGENCE
-- Configuracao de permissoes do Snowflake
-- Database: ENERGY_DB
-- Warehouse: ENERGY_WH
-- =====================================================

-- Execute com uma role administrativa autorizada.
-- Pressupoe que o database, warehouse, schemas e roles
-- ja existem.

-- =====================================================
-- ENERGY_ADMIN
-- Administracao dos objetos do projeto
-- =====================================================

GRANT USAGE ON DATABASE ENERGY_DB
TO ROLE ENERGY_ADMIN;

GRANT ALL PRIVILEGES ON DATABASE ENERGY_DB
TO ROLE ENERGY_ADMIN;

GRANT USAGE ON ALL SCHEMAS IN DATABASE ENERGY_DB
TO ROLE ENERGY_ADMIN;

GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE ENERGY_DB
TO ROLE ENERGY_ADMIN;

GRANT USAGE, OPERATE ON WAREHOUSE ENERGY_WH
TO ROLE ENERGY_ADMIN;


-- =====================================================
-- ENERGY_INGEST
-- Python -> RAW
-- =====================================================

GRANT USAGE ON DATABASE ENERGY_DB
TO ROLE ENERGY_INGEST;

GRANT USAGE ON SCHEMA ENERGY_DB.RAW
TO ROLE ENERGY_INGEST;

GRANT USAGE ON WAREHOUSE ENERGY_WH
TO ROLE ENERGY_INGEST;

-- Tabelas existentes no RAW
GRANT SELECT, INSERT, UPDATE, DELETE
ON ALL TABLES IN SCHEMA ENERGY_DB.RAW
TO ROLE ENERGY_INGEST;

-- Tabelas futuras no RAW
GRANT SELECT, INSERT, UPDATE, DELETE
ON FUTURE TABLES IN SCHEMA ENERGY_DB.RAW
TO ROLE ENERGY_INGEST;


-- =====================================================
-- ENERGY_DBT
-- RAW -> STAGING -> INTERMEDIATE -> MART
-- =====================================================

GRANT USAGE ON DATABASE ENERGY_DB
TO ROLE ENERGY_DBT;

GRANT USAGE ON WAREHOUSE ENERGY_WH
TO ROLE ENERGY_DBT;

-- Leitura dos dados de origem
GRANT USAGE ON SCHEMA ENERGY_DB.RAW
TO ROLE ENERGY_DBT;

GRANT SELECT ON ALL TABLES IN SCHEMA ENERGY_DB.RAW
TO ROLE ENERGY_DBT;

GRANT SELECT ON FUTURE TABLES IN SCHEMA ENERGY_DB.RAW
TO ROLE ENERGY_DBT;

-- STAGING: views e tabelas de staging
GRANT USAGE ON SCHEMA ENERGY_DB.STAGING
TO ROLE ENERGY_DBT;

GRANT CREATE VIEW, CREATE TABLE
ON SCHEMA ENERGY_DB.STAGING
TO ROLE ENERGY_DBT;

-- INTERMEDIATE: modelos intermediarios
GRANT USAGE ON SCHEMA ENERGY_DB.INTERMEDIATE
TO ROLE ENERGY_DBT;

GRANT CREATE VIEW, CREATE TABLE
ON SCHEMA ENERGY_DB.INTERMEDIATE
TO ROLE ENERGY_DBT;

-- MART: tabelas e views para consumo analitico
GRANT USAGE ON SCHEMA ENERGY_DB.MART
TO ROLE ENERGY_DBT;

GRANT CREATE VIEW, CREATE TABLE
ON SCHEMA ENERGY_DB.MART
TO ROLE ENERGY_DBT;


-- =====================================================
-- ENERGY_READONLY
-- Power BI -> MART
-- =====================================================

GRANT USAGE ON DATABASE ENERGY_DB
TO ROLE ENERGY_READONLY;

GRANT USAGE ON SCHEMA ENERGY_DB.MART
TO ROLE ENERGY_READONLY;

GRANT USAGE ON WAREHOUSE ENERGY_WH
TO ROLE ENERGY_READONLY;

-- Leitura de tabelas e views existentes
GRANT SELECT ON ALL TABLES IN SCHEMA ENERGY_DB.MART
TO ROLE ENERGY_READONLY;

GRANT SELECT ON ALL VIEWS IN SCHEMA ENERGY_DB.MART
TO ROLE ENERGY_READONLY;

-- Leitura automatica de tabelas e views futuras
GRANT SELECT ON FUTURE TABLES IN SCHEMA ENERGY_DB.MART
TO ROLE ENERGY_READONLY;

GRANT SELECT ON FUTURE VIEWS IN SCHEMA ENERGY_DB.MART
TO ROLE ENERGY_READONLY;
